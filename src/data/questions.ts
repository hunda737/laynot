import type { Localized } from '@/i18n';

export type CategoryId = 'ethiopia' | 'geography' | 'football' | 'science' | 'entertainment' | 'movies' | 'general';

export type Difficulty = 'easy' | 'medium' | 'hard';
export const DIFFICULTIES: Difficulty[] = ['easy', 'medium', 'hard'];

export interface Question {
  id: string;
  category: CategoryId;
  difficulty: Difficulty;
  text: Localized;
  /** The first choice is always the correct one. The play screen shuffles the order. */
  choices: [Localized, Localized, Localized, Localized];
  fact: Localized;
}

type Pair = [en: string, am: string];

const L = ([en, am]: Pair): Localized => ({ en, am });
const LEVEL = { e: 'easy', m: 'medium', h: 'hard' } as const;

function q(
  id: string,
  category: CategoryId,
  level: keyof typeof LEVEL,
  text: Pair,
  choices: [Pair, Pair, Pair, Pair],
  fact: Pair,
): Question {
  return {
    id,
    category,
    difficulty: LEVEL[level],
    text: L(text),
    choices: choices.map(L) as Question['choices'],
    fact: L(fact),
  };
}

